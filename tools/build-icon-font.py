#!/usr/bin/env python3
"""tools/build-icon-font.py — build a tree-shaken, self-hosted Font Awesome
Solid icon font for OpenKnowledge.

Why: the app used the FA CDN (only runtime network dependency — broke the
offline/file:// promise), then moved to inline Lucide-style SVG. The
requested direction is FA *solid* glyphs again, but without resurrecting
the CDN dependency. So we:

  1. Read icon names from src/utils/icons.js — the single source of truth
     (ICON_NAMES = canonical FA6 free-solid names, ALIASES = legacy /
     Lucide / Material-Symbols names mapped onto them).
  2. Resolve every canonical name to its FA codepoint from the official
     Font Awesome 6.5.2 all.min.css.
  3. Subset fa-solid-900.ttf to just those glyphs with fontTools
     (full font ~420 KB TTF → a few KB woff2).
  4. Emit public/fonts/fa-solid-900.min.woff2 plus a tiny
     src/styles/vendor/fa-solid.css (@font-face + .fa-solid base +
     one ::before rule per icon).

Usage:
    curl -sf -o /tmp/fa/all.min.css https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2/css/all.min.css
    curl -sf -o /tmp/fa/fa-solid-900.ttf https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2/webfonts/fa-solid-900.ttf
    python3 tools/build-icon-font.py

A canonical name missing from FA's CSS fails the build loudly — new icons
must be real FA6 free-solid names, not invented ones.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ICONS_JS = REPO / "src" / "utils" / "icons.js"
FA_CSS = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/fa/all.min.css")
FA_TTF = Path(sys.argv[2] if len(sys.argv) > 2 else "/tmp/fa/fa-solid-900.ttf")
OUT_FONT_DIR = REPO / "public" / "fonts"
OUT_CSS = REPO / "src" / "styles" / "vendor" / "fa-solid.css"
FONT_URL = "../../public/fonts/fa-solid-900.min.woff2"  # relative from src/styles/vendor/


def read_names_from_icons_js():
    """Parse ICON_NAMES + ALIASES out of src/utils/icons.js."""
    src = ICONS_JS.read_text(encoding="utf-8")

    m_names = re.search(r"export const ICON_NAMES = \[(.*?)\];", src, re.S)
    if not m_names:
        raise SystemExit("ERROR: ICON_NAMES not found in icons.js")
    names = re.findall(r'"([a-z0-9-]+)"', m_names.group(1))

    m_alias = re.search(r"export const ALIASES = \{(.*?)\n\};", src, re.S)
    aliases = {}
    if m_alias:
        for key, val in re.findall(r'["\']?([A-Za-z0-9_-]+)["\']?:\s*"([a-z0-9-]+)"', m_alias.group(1)):
            aliases[key] = val

    return names, aliases


def resolve_codepoints(css: str, names: set) -> dict:
    """FA's minified CSS groups aliases into one rule:
    `.fa-ban:before,.fa-cancel:before{content:"\\f05e"}` — so match per
    rule: selector-list + content codepoint, then index by icon name."""
    cp = {}
    rules = re.findall(r'([^{}]+)\{content:"\\([0-9a-f]+)"', css)
    for selectors, code in rules:
        for sel in selectors.split(","):
            m = re.match(r"\.fa-([a-z0-9-]+):before$", sel.strip())
            if m and m.group(1) in names and m.group(1) not in cp:
                cp[m.group(1)] = code
    missing = names - set(cp)
    if missing:
        raise SystemExit(
            "ERROR: icons not found in FA CSS — use real FA6 free-solid names: "
            + ", ".join(sorted(missing))
        )
    return cp


def main() -> None:
    if not FA_CSS.exists() or not FA_TTF.exists():
        raise SystemExit(
            "FA assets missing. Download Font Awesome 6.5.2 first:\n"
            "  curl -sf -o /tmp/fa/all.min.css https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2/css/all.min.css\n"
            "  curl -sf -o /tmp/fa/fa-solid-900.ttf https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2/webfonts/fa-solid-900.ttf"
        )

    icon_names, aliases = read_names_from_icons_js()
    canonical_names = {aliases.get(n, n) for n in icon_names} | set(aliases.values())
    # drop non-glyph alias targets that are themselves aliases
    canonical_names = {aliases.get(n, n) for n in canonical_names}

    css = FA_CSS.read_text(encoding="utf-8")
    cp = resolve_codepoints(css, canonical_names)

    OUT_FONT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_CSS.parent.mkdir(parents=True, exist_ok=True)

    codepoints_arg = ",".join(f"U+{v}" for v in sorted(set(cp.values())))
    woff2_out = OUT_FONT_DIR / "fa-solid-900.min.woff2"
    subprocess.run(
        [
            sys.executable, "-m", "fontTools.subset", str(FA_TTF),
            f"--unicodes={codepoints_arg}",
            "--flavor=woff2",
            f"--output-file={woff2_out}",
            "--layout-features=*",
            "--no-hinting",
            "--desubroutinize",
        ],
        check=True,
    )

    lines = [
        "/* src/styles/vendor/fa-solid.css — GENERATED by tools/build-icon-font.py.",
        "   Do not edit by hand: re-run `python3 tools/build-icon-font.py` after",
        "   changing icon names in src/utils/icons.js. Font Awesome 6 Free",
        "   (solid) subsetted to the glyphs this app uses — self-hosted,",
        "   offline-safe, a few KB instead of the ~150 KB CDN font. */",
        "@font-face {",
        '  font-family: "Font Awesome 6 Free";',
        "  font-style: normal;",
        "  font-weight: 900;",
        "  font-display: block;",
        f"  src: url('{FONT_URL}') format('woff2');",
        "}",
        "",
        "/* Minimal rewrite of FA's .fa-solid base: same metrics contract,",
        "   no dependency on the full all.min.css. */",
        ".fa-solid, .fas {",
        '  font-family: "Font Awesome 6 Free";',
        "  font-weight: 900;",
        "  font-style: normal;",
        "  font-variant: normal;",
        "  text-rendering: auto;",
        "  line-height: 1;",
        "  display: inline-block;",
        "  -webkit-font-smoothing: antialiased;",
        "  -moz-osx-font-smoothing: grayscale;",
        "}",
        "",
    ]
    for name in sorted(cp):
        lines.append(f'.fa-{name}::before {{ content: "\\{cp[name]}"; }}')
    OUT_CSS.write_text("\n".join(lines) + "\n", encoding="utf-8")

    kb = woff2_out.stat().st_size / 1024
    print(f"OK: {len(cp)} glyphs subsetted -> {woff2_out} ({kb:.1f} KB)")
    print(f"OK: CSS written -> {OUT_CSS}")


if __name__ == "__main__":
    main()
